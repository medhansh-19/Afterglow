"""Remove historical toolchain DLLs after successful NSIS resource installation.

Use an explicit historical list, never a wildcard over user files. Exclude every
incoming DLL so baseline bundles and future SDK additions remain intact.
"""
import argparse
import json
from pathlib import Path
import re


def generate(runtime, obsolete, output):
    if not runtime.is_dir():
        raise ValueError("Stage the private runtime before generating installer hooks.")
    source = json.loads(obsolete.read_text(encoding="utf-8-sig"))
    if source.get("schemaVersion") != 1 or not isinstance(source.get("libraries"), list):
        raise ValueError("Invalid obsolete runtime manifest.")
    incoming = {p.name.lower() for p in runtime.iterdir() if p.is_file() and p.suffix.lower() == ".dll"}
    names = {}
    for name in source["libraries"]:
        if not isinstance(name, str) or not re.fullmatch(r"[A-Za-z0-9_+-]+(?:\.[A-Za-z0-9_+-]+)*\.dll", name, re.I):
            raise ValueError(f"Invalid historical DLL name: {name!r}")
        if name.lower() not in incoming:
            names[name.lower()] = name
    lines = [
        '; Generated by windows/scripts/generate-installer-hooks.py; do not edit.',
        '!include LogicLib.nsh',
        '!macro NSIS_HOOK_POSTINSTALL',
        '  ; The new private runtime is installed before old, unused tools are removed.',
        '  ; Never touch application data, unknown files, or any incoming runtime DLL.',
    ]
    for _, name in sorted(names.items()):
        target = '$INSTDIR\\runtime\\' + name
        lines.extend([
            '  ClearErrors',
            f'  Delete "{target}"',
            f'  ${{If}} ${{FileExists}} "{target}"',
            f'    DetailPrint "Could not remove obsolete runtime file: {name}"',
            '    SetErrorLevel 1',
            '    Abort "Close programs using Afterglow runtime files and run setup again."',
            '  ${EndIf}',
        ])
    lines.extend(['  ClearErrors', '!macroend', ''])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines), encoding='utf-8')
    print(f'Generated post-install cleanup for {len(names)} historical DLLs; retained all {len(incoming)} incoming DLLs.')
    return sorted(names.values(), key=str.lower)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--runtime', type=Path, required=True)
    parser.add_argument('--obsolete', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    generate(args.runtime, args.obsolete, args.output)
